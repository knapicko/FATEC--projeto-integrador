CREATE TABLE IF NOT EXISTS public.pagamentos_stripe (
  id_pagamento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_solicitacao bigint NOT NULL
    REFERENCES public.solicitacoes(id_solicitacao),
  stripe_payment_intent_id text NOT NULL UNIQUE,
  stripe_charge_id text,
  metodo_pagamento text NOT NULL,
  status text NOT NULL,
  valor_centavos bigint NOT NULL,
  moeda text NOT NULL DEFAULT 'brl',
  pix_copia_cola text,
  pix_qr_code_url text,
  ultimo_evento_stripe text,
  data_criacao timestamptz NOT NULL DEFAULT now(),
  data_atualizacao timestamptz NOT NULL DEFAULT now(),
  data_pagamento timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS pagamentos_stripe_solicitacao_uidx
  ON public.pagamentos_stripe (fk_solicitacao);

CREATE INDEX IF NOT EXISTS pagamentos_stripe_solicitacao_idx
  ON public.pagamentos_stripe (fk_solicitacao);

ALTER TABLE public.pagamentos_stripe ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "pagamentos_stripe_select_cliente"
  ON public.pagamentos_stripe;
CREATE POLICY "pagamentos_stripe_select_cliente"
  ON public.pagamentos_stripe FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.solicitacoes s
      JOIN public.usuarios u ON u.id_usuario = s.fk_usuario
      WHERE s.id_solicitacao = pagamentos_stripe.fk_solicitacao
        AND u.auth_id = auth.uid()
    )
  );

ALTER TABLE public.dados_profissionais
  ADD COLUMN IF NOT EXISTS stripe_connected_account_id text;

ALTER TABLE public.grupo_empresa
  ADD COLUMN IF NOT EXISTS stripe_connected_account_id text;
