-- ============================================================================
-- ConsertaJá — Solicitação Geográfica v5: proposta de preço
-- Rode DEPOIS de migration_oficios_por_categoria.sql.
--
-- Antes: o profissional informava o valor e a `solicitacoes` já nascia.
-- Agora:
--   1. o profissional ENVIA UMA PROPOSTA (valor) → tabela propostas_geograficas
--      (status 44 "Proposta Enviada"); a solicitação geográfica fica em 44 e
--      some do Radar dos outros profissionais;
--   2. o cliente ACEITA → nasce a `solicitacoes` (status 2, Aguardando
--      Pagamento), proposta 46 "Proposta Aceita", geográfica 42;
--      ou RECUSA → proposta 45 "Proposta Recusada" e a geográfica volta a
--      39 (aberta de novo no Radar, inclusive para o mesmo profissional mandar
--      outro valor).
--
-- Status novos (tipo "Solicitação Geográfica"): 44, 45, 46.
-- Tudo numa transação: se algo falhar, nada muda.
-- ============================================================================

BEGIN;

-- 1) Status ------------------------------------------------------------------------
DO $$
DECLARE
  v record;
BEGIN
  -- Não sobrescreve status de outro tipo que já use estes ids.
  FOR v IN
    SELECT id_status, tipo_status::text AS tipo, status
    FROM public.status
    WHERE id_status IN (44, 45, 46)
      AND tipo_status::text <> 'Solicitação Geográfica'
  LOOP
    RAISE EXCEPTION 'O id_status % já é usado por "%" (%). Troque os ids 44/45/46 neste script e no app (StatusPropostaGeo).',
      v.id_status, v.status, v.tipo;
  END LOOP;
END $$;

INSERT INTO public.status (id_status, tipo_status, status)
OVERRIDING SYSTEM VALUE
VALUES
  (44, 'Solicitação Geográfica', 'Proposta Enviada'),
  (45, 'Solicitação Geográfica', 'Proposta Recusada'),
  (46, 'Solicitação Geográfica', 'Proposta Aceita')
ON CONFLICT (id_status) DO UPDATE
SET tipo_status = EXCLUDED.tipo_status,
    status      = EXCLUDED.status;

-- Se a coluna for IDENTITY, a sequência não pode gerar estes ids depois.
DO $$
BEGIN
  PERFORM setval(
    pg_get_serial_sequence('public.status', 'id_status'),
    greatest((SELECT max(id_status) FROM public.status), 46));
EXCEPTION WHEN others THEN
  NULL; -- sem sequência associada: nada a fazer
END $$;

-- 2) Propostas -----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.propostas_geograficas (
  id_proposta               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_solicitacao_geografica bigint NOT NULL
    REFERENCES public.solicitacoes_geograficas (id_solicitacao_geografica) ON DELETE CASCADE,
  fk_profissional           bigint NOT NULL
    REFERENCES public.dados_profissionais (id_profissional) ON DELETE CASCADE,
  fk_grupo_empresa          bigint
    REFERENCES public.grupo_empresa (id_grupo_empresa) ON DELETE CASCADE,
  valor                     numeric(10, 2) NOT NULL CHECK (valor > 0),
  fk_status                 bigint NOT NULL DEFAULT 44
    REFERENCES public.status (id_status),
  data_envio                timestamptz NOT NULL DEFAULT now(),
  data_resposta             timestamptz,
  fk_solicitacao            bigint
    REFERENCES public.solicitacoes (id_solicitacao) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS propostas_geo_fk_geo_idx
  ON public.propostas_geograficas (fk_solicitacao_geografica);
CREATE INDEX IF NOT EXISTS propostas_geo_fk_prof_idx
  ON public.propostas_geograficas (fk_profissional, data_envio DESC);
-- Uma proposta pendente por vez em cada solicitação geográfica.
CREATE UNIQUE INDEX IF NOT EXISTS propostas_geo_uma_pendente_uidx
  ON public.propostas_geograficas (fk_solicitacao_geografica)
  WHERE fk_status = 44;

-- Só as RPCs abaixo (SECURITY DEFINER) leem/escrevem.
ALTER TABLE public.propostas_geograficas ENABLE ROW LEVEL SECURITY;

-- 3) Profissional envia a proposta -------------------------------------------------
DROP FUNCTION IF EXISTS public.aceitar_solicitacao_geografica(bigint, numeric, boolean);

CREATE OR REPLACE FUNCTION public.enviar_proposta_geografica(
  p_id_solicitacao_geografica bigint,
  p_valor                     numeric,
  p_conta_empresa             boolean DEFAULT false
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_usuario bigint := public.meu_id_usuario();
  v_geo     public.solicitacoes_geograficas%ROWTYPE;
  v_prof    bigint;
  v_grupo   bigint;
  v_id      bigint;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Sessão expirada. Entre novamente.' USING ERRCODE = '42501';
  END IF;
  IF p_valor IS NULL OR p_valor <= 0 THEN
    RAISE EXCEPTION 'Informe o valor do serviço.';
  END IF;

  SELECT * INTO v_geo
  FROM public.solicitacoes_geograficas
  WHERE id_solicitacao_geografica = p_id_solicitacao_geografica
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Solicitação não encontrada.';
  END IF;
  IF v_geo.fk_status = 44 THEN
    RAISE EXCEPTION 'Outro profissional já enviou uma proposta. Aguarde a resposta do cliente.';
  END IF;
  IF v_geo.fk_status NOT IN (39, 41) THEN
    RAISE EXCEPTION 'Esta solicitação não está mais disponível.';
  END IF;
  IF v_geo.fk_usuario = v_usuario THEN
    RAISE EXCEPTION 'Você não pode enviar proposta para o seu próprio pedido.';
  END IF;

  IF coalesce(p_conta_empresa, false) THEN
    SELECT dp.id_profissional, g.id_grupo_empresa
      INTO v_prof, v_grupo
    FROM public.dados_profissionais dp
    JOIN public.grupo_empresa g
      ON g.fk_perfil = dp.fk_perfil OR g.id_grupo_empresa = dp.fk_grupo_empresa
    WHERE dp.fk_usuario = v_usuario
    ORDER BY coalesce(g.fk_perfil = dp.fk_perfil, false) DESC
    LIMIT 1;

    IF v_grupo IS NULL THEN
      RAISE EXCEPTION 'Nenhuma empresa encontrada para a sua conta.';
    END IF;
    IF v_geo.fk_funcao NOT IN (SELECT f.fk_funcao FROM public.radar_funcoes_perfil(NULL, v_grupo) f) THEN
      RAISE EXCEPTION 'A empresa não atende a área deste pedido.';
    END IF;
  ELSE
    SELECT dp.id_profissional INTO v_prof
    FROM public.dados_profissionais dp
    WHERE dp.fk_usuario = v_usuario
    ORDER BY (v_geo.fk_funcao IN (
               SELECT f.fk_funcao FROM public.radar_funcoes_perfil(dp.id_profissional, NULL) f)) DESC,
             dp.id_profissional
    LIMIT 1;

    IF v_prof IS NULL THEN
      RAISE EXCEPTION 'Perfil profissional não encontrado.';
    END IF;
    IF v_geo.fk_funcao NOT IN (SELECT f.fk_funcao FROM public.radar_funcoes_perfil(v_prof, NULL) f) THEN
      RAISE EXCEPTION 'Você não atende a área deste pedido.';
    END IF;
    v_grupo := NULL;
  END IF;

  INSERT INTO public.propostas_geograficas
    (fk_solicitacao_geografica, fk_profissional, fk_grupo_empresa, valor)
  VALUES
    (v_geo.id_solicitacao_geografica, v_prof, v_grupo, round(p_valor, 2))
  RETURNING id_proposta INTO v_id;

  UPDATE public.solicitacoes_geograficas
  SET fk_status = 44
  WHERE id_solicitacao_geografica = v_geo.id_solicitacao_geografica;

  RETURN v_id;
END;
$$;

GRANT EXECUTE ON FUNCTION public.enviar_proposta_geografica(bigint, numeric, boolean)
  TO authenticated;

-- 4) Cliente responde -----------------------------------------------------------------
-- Aceitar: devolve o id da `solicitacoes` criada. Recusar: devolve null.
CREATE OR REPLACE FUNCTION public.responder_proposta_geografica(
  p_id_proposta bigint,
  p_aceitar     boolean
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_usuario bigint := public.meu_id_usuario();
  v_prop    public.propostas_geograficas%ROWTYPE;
  v_geo     public.solicitacoes_geograficas%ROWTYPE;
  v_temp    bigint;
  v_sol     bigint;
BEGIN
  SELECT * INTO v_prop
  FROM public.propostas_geograficas
  WHERE id_proposta = p_id_proposta
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Proposta não encontrada.';
  END IF;

  SELECT * INTO v_geo
  FROM public.solicitacoes_geograficas
  WHERE id_solicitacao_geografica = v_prop.fk_solicitacao_geografica
  FOR UPDATE;

  IF v_geo.fk_usuario IS DISTINCT FROM v_usuario THEN
    RAISE EXCEPTION 'Proposta não encontrada.';
  END IF;
  IF v_prop.fk_status <> 44 THEN
    RAISE EXCEPTION 'Esta proposta já foi respondida.';
  END IF;

  IF NOT coalesce(p_aceitar, false) THEN
    UPDATE public.propostas_geograficas
    SET fk_status = 45, data_resposta = now()
    WHERE id_proposta = v_prop.id_proposta;

    -- Volta para o Radar.
    UPDATE public.solicitacoes_geograficas
    SET fk_status = 39
    WHERE id_solicitacao_geografica = v_geo.id_solicitacao_geografica;
    RETURN NULL;
  END IF;

  INSERT INTO public.servicos_chat_temporarios
    (titulo, descricao, valor, imagem_url, ativo, fk_profissional,
     fk_grupo_empresa, fk_oficios, fk_funcao, tipo_execucao, carga_servico)
  VALUES
    (v_geo.titulo, v_geo.descricao, v_prop.valor, v_geo.img_solicitacao[1],
     true, v_prop.fk_profissional, v_prop.fk_grupo_empresa, v_geo.fk_oficio,
     v_geo.fk_funcao, v_geo.metodo_entrega, 'Médio')
  RETURNING id_servico_temp INTO v_temp;

  INSERT INTO public.solicitacoes
    (data_solicitacao, data_aceite, valor_final, fk_usuario, fk_profissional,
     fk_status, fk_servico_prof, fk_servico_temp, fk_endereco, fk_grupo_empresa,
     tipo_execucao, detalhes, data_agendada, hora_agendada, hora_agendada_fim,
     etapa_solicitacao, imagens_anexadas_cliente, fk_solicitacao_geografica)
  VALUES
    (v_geo.data_criacao, now(), v_prop.valor, v_geo.fk_usuario, v_prop.fk_profissional,
     2, NULL, v_temp, v_geo.endereco_proximo, v_prop.fk_grupo_empresa,
     v_geo.metodo_entrega, v_geo.descricao, NULL, NULL, NULL,
     1, v_geo.img_solicitacao, v_geo.id_solicitacao_geografica)
  RETURNING id_solicitacao INTO v_sol;

  UPDATE public.propostas_geograficas
  SET fk_status = 46, data_resposta = now(), fk_solicitacao = v_sol
  WHERE id_proposta = v_prop.id_proposta;

  UPDATE public.solicitacoes_geograficas
  SET fk_status = 42
  WHERE id_solicitacao_geografica = v_geo.id_solicitacao_geografica;

  RETURN v_sol;
END;
$$;

GRANT EXECUTE ON FUNCTION public.responder_proposta_geografica(bigint, boolean)
  TO authenticated;

-- 5) Cancelar (cliente): também com proposta pendente ----------------------------
CREATE OR REPLACE FUNCTION public.cancelar_solicitacao_geografica(
  p_id_solicitacao_geografica bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_usuario bigint := public.meu_id_usuario();
  v_geo     public.solicitacoes_geograficas%ROWTYPE;
  v_sol     public.solicitacoes%ROWTYPE;
BEGIN
  SELECT * INTO v_geo
  FROM public.solicitacoes_geograficas
  WHERE id_solicitacao_geografica = p_id_solicitacao_geografica
  FOR UPDATE;

  IF NOT FOUND OR v_geo.fk_usuario IS DISTINCT FROM v_usuario THEN
    RAISE EXCEPTION 'Solicitação não encontrada.';
  END IF;

  IF v_geo.fk_status IN (39, 41, 44) THEN
    -- Proposta pendente conta como recusada.
    UPDATE public.propostas_geograficas
    SET fk_status = 45, data_resposta = now()
    WHERE fk_solicitacao_geografica = v_geo.id_solicitacao_geografica
      AND fk_status = 44;

    UPDATE public.solicitacoes_geograficas SET fk_status = 43
    WHERE id_solicitacao_geografica = v_geo.id_solicitacao_geografica;
    RETURN;
  END IF;

  IF v_geo.fk_status = 42 THEN
    SELECT * INTO v_sol FROM public.solicitacoes
    WHERE fk_solicitacao_geografica = v_geo.id_solicitacao_geografica
    FOR UPDATE;

    IF NOT FOUND THEN
      UPDATE public.solicitacoes_geograficas SET fk_status = 43
      WHERE id_solicitacao_geografica = v_geo.id_solicitacao_geografica;
      RETURN;
    END IF;
    IF v_sol.fk_status NOT IN (1, 2) THEN
      RAISE EXCEPTION 'O pagamento já foi feito. Para cancelar, fale com o profissional pelo chat.';
    END IF;

    UPDATE public.solicitacoes SET fk_status = 7
    WHERE id_solicitacao = v_sol.id_solicitacao;  -- trigger → geográfica 40
  END IF;
END;
$$;

-- 6) Profissional: as propostas dele -------------------------------------------------
-- Pendentes, recusadas nos últimos 7 dias e aceitas ainda não concluídas.
DROP FUNCTION IF EXISTS public.solicitacoes_geograficas_aceitas(boolean);

CREATE OR REPLACE FUNCTION public.minhas_propostas_geograficas(
  p_conta_empresa boolean DEFAULT false
)
RETURNS TABLE (
  id_proposta       bigint,
  status_proposta   bigint,
  valor_proposta    numeric,
  data_envio        timestamptz,
  data_resposta     timestamptz,
  id_solicitacao_geografica bigint,
  titulo            text,
  descricao         text,
  img_solicitacao   text[],
  funcao            text,
  cor               text,
  metodo_entrega    text,
  latitude          double precision,
  longitude         double precision,
  data_criacao      timestamptz,
  id_solicitacao    bigint,
  fk_status         bigint,
  status            text,
  etapa_solicitacao integer,
  valor_final       numeric,
  data_aceite       timestamptz,
  nome_cliente      text,
  foto_cliente      text,
  endereco_cliente  text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
SELECT p.id_proposta,
       p.fk_status,
       p.valor,
       p.data_envio,
       p.data_resposta,
       sg.id_solicitacao_geografica,
       sg.titulo,
       sg.descricao,
       sg.img_solicitacao,
       f.funcao::text,
       o.cor::text,
       sg.metodo_entrega,
       sg.latitude,
       sg.longitude,
       sg.data_criacao,
       s.id_solicitacao,
       s.fk_status,
       st.status::text,
       s.etapa_solicitacao,
       s.valor_final,
       s.data_aceite,
       u.nome::text,
       NULLIF(NULLIF(u.foto_perfil_url::text, ''), 'null'),
       (
         SELECT NULLIF(concat_ws(' - ',
                  NULLIF(concat_ws(', ', NULLIF(e.logradouro::text, ''), NULLIF(e.numero::text, '')), ''),
                  NULLIF(concat_ws(', ', NULLIF(e.bairro::text, ''), NULLIF(es.sigla_estado::text, '')), '')), '')
         FROM public.enderecos e
         LEFT JOIN public.cidades ci ON ci.id_cidade = e.fk_cidade
         LEFT JOIN public.estados es ON es.id_estado = ci.fk_estado
         WHERE e.id_endereco = coalesce(s.fk_endereco, sg.endereco_proximo)
       )
FROM public.propostas_geograficas p
JOIN public.solicitacoes_geograficas sg
  ON sg.id_solicitacao_geografica = p.fk_solicitacao_geografica
JOIN public.funcoes f ON f.id_funcao = sg.fk_funcao
LEFT JOIN public.oficios o ON o.id_oficio = f.fk_oficio
LEFT JOIN public.solicitacoes s ON s.id_solicitacao = p.fk_solicitacao
LEFT JOIN public.status st ON st.id_status = s.fk_status
JOIN public.usuarios u ON u.id_usuario = sg.fk_usuario
WHERE public.profissional_pode_acessar_solicitacao(p.fk_profissional, p.fk_grupo_empresa)
  AND (p.fk_grupo_empresa IS NOT NULL) = coalesce(p_conta_empresa, false)
  AND (
        p.fk_status = 44
     OR (p.fk_status = 45 AND p.data_resposta > now() - interval '7 days')
     OR (p.fk_status = 46 AND coalesce(s.fk_status, 0) NOT IN (6, 7))
  )
ORDER BY p.data_envio DESC;
$$;

GRANT EXECUTE ON FUNCTION public.minhas_propostas_geograficas(boolean) TO authenticated;

-- 7) Cliente: proposta pendente ou aceita (+ solicitação vinculada) ------------
DROP FUNCTION IF EXISTS public.acompanhamento_solicitacao_geografica(bigint);

CREATE OR REPLACE FUNCTION public.acompanhamento_solicitacao_geografica(
  p_id_solicitacao_geografica bigint
)
RETURNS TABLE (
  id_proposta       bigint,
  status_proposta   bigint,
  id_solicitacao    bigint,
  fk_status         bigint,
  status            text,
  etapa_solicitacao integer,
  valor_final       numeric,
  tipo_execucao     text,
  eh_empresa        boolean,
  id_profissional   bigint,
  id_grupo_empresa  bigint,
  nome              text,
  foto_url          text,
  tag_empresa       text,
  cor_tag_empresa   text,
  nota              numeric,
  total_avaliacoes  bigint,
  latitude          double precision,
  longitude         double precision
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
WITH base AS (
  SELECT p.*, sg.metodo_entrega
  FROM public.propostas_geograficas p
  JOIN public.solicitacoes_geograficas sg
    ON sg.id_solicitacao_geografica = p.fk_solicitacao_geografica
  WHERE sg.id_solicitacao_geografica = p_id_solicitacao_geografica
    AND sg.fk_usuario = public.meu_id_usuario()
    AND p.fk_status IN (44, 46)
  ORDER BY p.data_envio DESC
  LIMIT 1
),
aval AS (
  SELECT round(avg(av.nota)::numeric, 1) AS nota, count(*) AS total
  FROM public.avaliacoes_solicitacao av
  JOIN public.solicitacoes s2 ON s2.id_solicitacao = av.fk_solicitacao
  JOIN base b ON (b.fk_grupo_empresa IS NOT NULL AND s2.fk_grupo_empresa = b.fk_grupo_empresa)
              OR (b.fk_grupo_empresa IS NULL AND s2.fk_profissional = b.fk_profissional)
  WHERE av.tipo_avaliacao::text = 'profissional'
)
SELECT b.id_proposta,
       b.fk_status,
       s.id_solicitacao,
       s.fk_status,
       st.status::text,
       s.etapa_solicitacao,
       coalesce(s.valor_final, b.valor),
       coalesce(s.tipo_execucao, b.metodo_entrega),
       (b.fk_grupo_empresa IS NOT NULL),
       b.fk_profissional,
       b.fk_grupo_empresa,
       CASE WHEN b.fk_grupo_empresa IS NOT NULL THEN g.nome_empresa::text ELSE u.nome::text END,
       CASE WHEN b.fk_grupo_empresa IS NOT NULL THEN NULLIF(g.foto_url_empresa::text, '')
            ELSE NULLIF(NULLIF(u.foto_perfil_url::text, ''), 'null') END,
       NULLIF(g.tag_empresa::text, ''),
       NULLIF(g.cor_tag_empresa::text, ''),
       (SELECT nota FROM aval),
       (SELECT total FROM aval),
       loc.latitude,
       loc.longitude
FROM base b
LEFT JOIN public.solicitacoes s ON s.id_solicitacao = b.fk_solicitacao
LEFT JOIN public.status st ON st.id_status = s.fk_status
LEFT JOIN public.dados_profissionais dp ON dp.id_profissional = b.fk_profissional
LEFT JOIN public.usuarios u ON u.id_usuario = dp.fk_usuario
LEFT JOIN public.grupo_empresa g ON g.id_grupo_empresa = b.fk_grupo_empresa
LEFT JOIN LATERAL (
  SELECT l.latitude, l.longitude
  FROM public.radar_locais_perfis() l
  WHERE (b.fk_grupo_empresa IS NOT NULL AND l.id_grupo_empresa = b.fk_grupo_empresa)
     OR (b.fk_grupo_empresa IS NULL AND l.id_profissional = b.fk_profissional)
  LIMIT 1
) loc ON true;
$$;

GRANT EXECUTE ON FUNCTION public.acompanhamento_solicitacao_geografica(bigint) TO authenticated;

