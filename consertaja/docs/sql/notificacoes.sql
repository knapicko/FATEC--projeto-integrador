-- ============================================================================
-- ConsertaJá — Sistema de notificações (Supabase + FCM)
--
-- Rode DEPOIS de:
--   migration_solicitacoes_geograficas_v4.sql      (radar_locais_perfis, radar_km)
--   migration_oficios_por_categoria.sql             (radar_funcoes_perfil)
--   migration_solicitacoes_geograficas_v5_propostas.sql (propostas_geograficas)
--
-- Como funciona:
--   1. Eventos do banco (triggers) e rotinas (pg_cron) descobrem QUEM recebe e
--      chamam public.criar_notificacao(...), que grava em `notificacoes`
--      (com chave_unica para não duplicar).
--   2. Um trigger em `notificacoes` chama a Edge Function `enviar-notificacao`
--      via pg_net. Ela busca os tokens em `dispositivos_notificacao` e entrega
--      pelo FCM (API HTTP v1). A gravação NÃO depende da entrega: se o FCM
--      falhar ou o celular estiver offline, a notificação continua salva.
--   3. O app lê `notificacoes` (RLS: só as do próprio usuário) e escuta o
--      Realtime para contadores e a tela minhas_notificacoes.dart.
--
-- Somente o tipo `feedback` é disparado pelo app (notificação local); ele não
-- passa por aqui.
--
-- ANTES DE RODAR: habilite as extensões pg_net e pg_cron
-- (Dashboard → Database → Extensions) — o script também tenta habilitar.
-- DEPOIS DE RODAR: crie os 2 segredos do Vault (passo 11, no fim do arquivo).
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS pg_net;
CREATE EXTENSION IF NOT EXISTS pg_cron;

BEGIN;

-- 1) Tabelas -----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.notificacoes (
  id_notificacao bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_usuario     bigint NOT NULL
    REFERENCES public.usuarios (id_usuario) ON DELETE CASCADE,
  tipo           text NOT NULL CHECK (tipo IN (
                   'Sistema', 'Solicitação', 'Global', 'Conversa',
                   'radar_prof', 'radar_cliente', 'feedback')),
  titulo         text NOT NULL CHECK (char_length(trim(titulo)) BETWEEN 1 AND 140),
  conteudo       text NOT NULL DEFAULT '',
  data_criacao   timestamptz NOT NULL DEFAULT now(),
  aberta         boolean NOT NULL DEFAULT false,
  data_abertura  timestamptz,
  -- Tela que abre ao tocar (null = destino padrão do tipo, definido no app).
  tela_destino   text,
  -- Foto (cliente, remetente, profissional) mostrada na notificação.
  imagem_url     text,
  -- Referências opcionais (o que a notificação "é sobre").
  fk_solicitacao            bigint REFERENCES public.solicitacoes (id_solicitacao) ON DELETE SET NULL,
  fk_conversa               bigint REFERENCES public.conversas (id_conversa) ON DELETE CASCADE,
  fk_solicitacao_geografica bigint REFERENCES public.solicitacoes_geograficas (id_solicitacao_geografica) ON DELETE SET NULL,
  fk_status                 bigint REFERENCES public.status (id_status),
  -- Dados extras para o app (ids, nomes, papel do destinatário...).
  dados          jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Evita duplicadas: o mesmo evento gera sempre a mesma chave.
  chave_unica    text UNIQUE,
  -- Entrega pelo FCM (controlado pelo servidor).
  push_status    text NOT NULL DEFAULT 'pendente' CHECK (push_status IN (
                   'pendente', 'enviando', 'enviado', 'sem_dispositivo',
                   'falhou', 'nao_enviar')),
  push_tentativas integer NOT NULL DEFAULT 0,
  push_enviado_em timestamptz,
  push_erro      text
);

CREATE INDEX IF NOT EXISTS notificacoes_usuario_data_idx
  ON public.notificacoes (fk_usuario, data_criacao DESC);
CREATE INDEX IF NOT EXISTS notificacoes_usuario_nao_abertas_idx
  ON public.notificacoes (fk_usuario) WHERE NOT aberta;
CREATE INDEX IF NOT EXISTS notificacoes_push_pendente_idx
  ON public.notificacoes (data_criacao) WHERE push_status = 'pendente';
CREATE INDEX IF NOT EXISTS notificacoes_conversa_idx
  ON public.notificacoes (fk_conversa) WHERE fk_conversa IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.dispositivos_notificacao (
  id_dispositivo   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_usuario       bigint NOT NULL
    REFERENCES public.usuarios (id_usuario) ON DELETE CASCADE,
  token_fcm        text NOT NULL UNIQUE CHECK (char_length(token_fcm) > 20),
  plataforma       text NOT NULL DEFAULT 'android'
    CHECK (plataforma IN ('android', 'ios', 'web', 'outro')),
  -- Perfil ativo no aparelho: decide quais pendências do "Sistema" mandar.
  perfil_ativo     text NOT NULL DEFAULT 'cliente'
    CHECK (perfil_ativo IN ('cliente', 'independente', 'empresa')),
  data_criacao     timestamptz NOT NULL DEFAULT now(),
  data_atualizacao timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS dispositivos_notificacao_usuario_idx
  ON public.dispositivos_notificacao (fk_usuario, data_atualizacao DESC);

-- 2) RLS -----------------------------------------------------------------------------
ALTER TABLE public.notificacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dispositivos_notificacao ENABLE ROW LEVEL SECURITY;

