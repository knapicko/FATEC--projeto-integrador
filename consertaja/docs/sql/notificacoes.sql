CREATE POLICY "notificacoes_delete_proprias" ON public.notificacoes
  FOR DELETE TO authenticated
  USING (fk_usuario = public.meu_id_usuario());

-- O app só pode mudar `aberta`/`data_abertura`; criar é só pelo servidor.
REVOKE ALL ON public.notificacoes FROM anon;
REVOKE INSERT, UPDATE ON public.notificacoes FROM authenticated;
GRANT SELECT, DELETE ON public.notificacoes TO authenticated;
GRANT UPDATE (aberta, data_abertura) ON public.notificacoes TO authenticated;

