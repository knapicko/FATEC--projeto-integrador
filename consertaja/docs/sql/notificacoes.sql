    END IF;
  END LOOP;

  RETURN v_qtd;
END;
$$;

-- Já houve notificação desta pendência nas últimas 20 h?
CREATE OR REPLACE FUNCTION public.notif_sistema_recente(p_usuario bigint, p_pendencia text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.notificacoes n
    WHERE n.fk_usuario = p_usuario
      AND n.tipo = 'Sistema'
      AND n.dados->>'pendencia' = p_pendencia
      AND n.data_criacao > now() - interval '20 hours');
$$;

-- Cria a notificação de uma pendência profissional (se pendente e não recente).
CREATE OR REPLACE FUNCTION public.notif_sistema_item(
  p_usuario  bigint,
  p_hoje     text,
  p_perfil   text,
  p_item     text,
  p_pendente boolean,
  p_titulo   text,
  p_texto    text,
  p_tela     text
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_pendencia text := p_perfil || ':' || p_item;
BEGIN
  IF NOT coalesce(p_pendente, false)
     OR public.notif_sistema_recente(p_usuario, v_pendencia) THEN
    RETURN 0;
  END IF;
  PERFORM public.criar_notificacao(
    p_usuario, 'Sistema', p_titulo, p_texto, p_tela, NULL,
    NULL, NULL, NULL, NULL,
    jsonb_build_object('pendencia', v_pendencia, 'perfil', p_perfil, 'item', p_item),
    format('sis:%s:%s:%s', v_pendencia, p_usuario, p_hoje));
  RETURN 1;
END;
$$;

-- 10) Global (preparado para o futuro: envio por administradores) -------------------
-- Uso (SQL Editor / service_role):
--   SELECT public.enviar_notificacao_global('Título', 'Texto', NULL);
CREATE OR REPLACE FUNCTION public.enviar_notificacao_global(
  p_titulo       text,
  p_conteudo     text,
  p_tela_destino text DEFAULT NULL,
  p_tipo_conta   text DEFAULT NULL  -- 'Cliente' | 'Profissional' | null = todos
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_lote text := to_char(now(), 'YYYYMMDDHH24MISS');
  v_qtd  integer := 0;
  u      record;
BEGIN
  FOR u IN
    SELECT id_usuario FROM public.usuarios
    WHERE auth_id IS NOT NULL
      AND (p_tipo_conta IS NULL OR tipo_conta::text = p_tipo_conta)
  LOOP
    PERFORM public.criar_notificacao(
      u.id_usuario, 'Global', p_titulo, p_conteudo, p_tela_destino, NULL,
      NULL, NULL, NULL, NULL, jsonb_build_object('lote', v_lote),
      format('global:%s:%s', v_lote, u.id_usuario));
    v_qtd := v_qtd + 1;
  END LOOP;
  RETURN v_qtd;
END;
$$;

