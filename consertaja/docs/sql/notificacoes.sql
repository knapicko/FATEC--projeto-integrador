  FOR SELECT TO authenticated
  USING (fk_usuario = public.meu_id_usuario());

DROP POLICY IF EXISTS "dispositivos_delete_proprios" ON public.dispositivos_notificacao;
CREATE POLICY "dispositivos_delete_proprios" ON public.dispositivos_notificacao
  FOR DELETE TO authenticated
  USING (fk_usuario = public.meu_id_usuario());

-- Cadastro/atualização só pela RPC registrar_dispositivo_notificacao.
REVOKE ALL ON public.dispositivos_notificacao FROM anon;
REVOKE INSERT, UPDATE ON public.dispositivos_notificacao FROM authenticated;
GRANT SELECT, DELETE ON public.dispositivos_notificacao TO authenticated;

