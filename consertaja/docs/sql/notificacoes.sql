-- 3) RPCs do app -------------------------------------------------------------------
-- Registra/atualiza o token FCM do aparelho. Se o token já era de outra conta
-- (troca de login no mesmo celular), passa a ser deste usuário.
CREATE OR REPLACE FUNCTION public.registrar_dispositivo_notificacao(
  p_token        text,
  p_plataforma   text DEFAULT 'android',
  p_perfil_ativo text DEFAULT 'cliente'
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_usuario bigint := public.meu_id_usuario();
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Sessão expirada.' USING ERRCODE = '42501';
  END IF;
  IF coalesce(char_length(p_token), 0) <= 20 THEN
    RAISE EXCEPTION 'Token inválido.';
  END IF;

  INSERT INTO public.dispositivos_notificacao
    (fk_usuario, token_fcm, plataforma, perfil_ativo)
  VALUES
    (v_usuario, p_token,
     CASE WHEN p_plataforma IN ('android', 'ios', 'web') THEN p_plataforma ELSE 'outro' END,
     CASE WHEN p_perfil_ativo IN ('cliente', 'independente', 'empresa') THEN p_perfil_ativo ELSE 'cliente' END)
  ON CONFLICT (token_fcm) DO UPDATE
  SET fk_usuario       = EXCLUDED.fk_usuario,
      plataforma       = EXCLUDED.plataforma,
      perfil_ativo     = EXCLUDED.perfil_ativo,
      data_atualizacao = now();
END;
$$;

GRANT EXECUTE ON FUNCTION public.registrar_dispositivo_notificacao(text, text, text) TO authenticated;

-- Contadores dos sininhos e da aba Mensagens.
--   nao_lidas: notificações não abertas (sem as de Conversa: mensagens têm o
--              próprio contador);
--   mensagens_nao_lidas: mensagens recebidas ainda não lidas (mensagens.lida).
CREATE OR REPLACE FUNCTION public.contadores_notificacoes()
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
WITH eu AS (SELECT public.meu_id_usuario() AS id),
meus_perfis AS (
  SELECT dp.id_profissional, dp.fk_grupo_empresa, dp.fk_perfil
  FROM public.dados_profissionais dp
  WHERE dp.fk_usuario = (SELECT id FROM eu)
),
minhas_conversas AS (
  SELECT c.id_conversa
  FROM public.conversas c
  WHERE c.fk_usuario = (SELECT id FROM eu)
     OR c.fk_profissional IN (SELECT id_profissional FROM meus_perfis)
     OR c.fk_grupo_empresa IN (
          SELECT g.id_grupo_empresa FROM public.grupo_empresa g
          WHERE g.id_grupo_empresa IN (SELECT fk_grupo_empresa FROM meus_perfis)
             OR g.fk_perfil IN (SELECT fk_perfil FROM meus_perfis))
)
SELECT jsonb_build_object(
  'nao_lidas', (
    SELECT count(*) FROM public.notificacoes n
    WHERE n.fk_usuario = (SELECT id FROM eu)
      AND NOT n.aberta
      AND n.tipo <> 'Conversa'),
  'mensagens_nao_lidas', (
    SELECT count(*) FROM public.mensagens m
    WHERE m.fk_conversa IN (SELECT id_conversa FROM minhas_conversas)
      AND m.fk_remitente_usuario IS DISTINCT FROM (SELECT id FROM eu)
      AND coalesce(m.lida, false) = false)
);
$$;

GRANT EXECUTE ON FUNCTION public.contadores_notificacoes() TO authenticated;

-- Marca como abertas (todas quando p_ids for null).
CREATE OR REPLACE FUNCTION public.marcar_notificacoes_abertas(p_ids bigint[] DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_qtd integer;
BEGIN
  UPDATE public.notificacoes
  SET aberta = true, data_abertura = coalesce(data_abertura, now())
  WHERE fk_usuario = public.meu_id_usuario()
    AND NOT aberta
    AND (p_ids IS NULL OR id_notificacao = ANY (p_ids));
  GET DIAGNOSTICS v_qtd = ROW_COUNT;
  RETURN v_qtd;
END;
$$;

GRANT EXECUTE ON FUNCTION public.marcar_notificacoes_abertas(bigint[]) TO authenticated;

-- 4) Núcleo: criar notificação --------------------------------------------------
-- Usada por todos os eventos do servidor. Nunca duplica (chave_unica).
CREATE OR REPLACE FUNCTION public.criar_notificacao(
  p_fk_usuario   bigint,
  p_tipo         text,
  p_titulo       text,
  p_conteudo     text,
  p_tela_destino text DEFAULT NULL,
  p_imagem_url   text DEFAULT NULL,
  p_fk_solicitacao bigint DEFAULT NULL,
  p_fk_conversa  bigint DEFAULT NULL,
  p_fk_solicitacao_geografica bigint DEFAULT NULL,
  p_fk_status    bigint DEFAULT NULL,
  p_dados        jsonb DEFAULT '{}'::jsonb,
  p_chave_unica  text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_id bigint;
BEGIN
  IF p_fk_usuario IS NULL OR coalesce(trim(p_titulo), '') = '' THEN
    RETURN NULL;
  END IF;

  INSERT INTO public.notificacoes
    (fk_usuario, tipo, titulo, conteudo, tela_destino, imagem_url,
     fk_solicitacao, fk_conversa, fk_solicitacao_geografica, fk_status,
     dados, chave_unica, push_status)
  VALUES
    (p_fk_usuario, p_tipo, left(trim(p_titulo), 140), coalesce(p_conteudo, ''),
     p_tela_destino, NULLIF(NULLIF(trim(coalesce(p_imagem_url, '')), ''), 'null'),
     p_fk_solicitacao, p_fk_conversa, p_fk_solicitacao_geografica, p_fk_status,
     coalesce(p_dados, '{}'::jsonb), p_chave_unica,
     CASE WHEN p_tipo = 'feedback' THEN 'nao_enviar' ELSE 'pendente' END)
  ON CONFLICT (chave_unica) DO NOTHING
  RETURNING id_notificacao INTO v_id;

  RETURN v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.criar_notificacao(
  bigint, text, text, text, text, text, bigint, bigint, bigint, bigint, jsonb, text
) FROM PUBLIC, anon, authenticated;

-- Usuários (contas) de um perfil profissional e/ou da empresa (dono).
CREATE OR REPLACE FUNCTION public.notif_usuarios_profissionais(
  p_id_profissional  bigint,
  p_id_grupo_empresa bigint
)
RETURNS TABLE (fk_usuario bigint)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT dp.fk_usuario FROM public.dados_profissionais dp
  WHERE p_id_profissional IS NOT NULL AND dp.id_profissional = p_id_profissional
  UNION
  SELECT dp.fk_usuario
  FROM public.grupo_empresa g
  JOIN public.dados_profissionais dp ON dp.fk_perfil = g.fk_perfil
  WHERE p_id_grupo_empresa IS NOT NULL AND g.id_grupo_empresa = p_id_grupo_empresa;
$$;

-- Título do serviço de uma solicitação (catálogo do profissional ou do chat).
CREATE OR REPLACE FUNCTION public.notif_titulo_servico(p_id_solicitacao bigint)
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT coalesce(sp.titulo, st.titulo, 'Serviço')::text
  FROM public.solicitacoes s
  LEFT JOIN public.servicos_profissional sp ON sp.id_servico_prof = s.fk_servico_prof
  LEFT JOIN public.servicos_chat_temporarios st ON st.id_servico_temp = s.fk_servico_temp
  WHERE s.id_solicitacao = p_id_solicitacao;
$$;

CREATE OR REPLACE FUNCTION public.notif_formatar_reais(v numeric)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT 'R$ ' || replace(replace(replace(
           to_char(coalesce(v, 0), 'FM999G999G990D00'), ',', '#'), '.', ','), '#', '.')
$$;

-- 5) Envio do push (pg_net → Edge Function) ---------------------------------------
-- Lê a URL da função e o segredo compartilhado do Vault (passo 11). Sem eles,
-- a notificação fica salva com push_status = 'pendente' e é reenviada depois.
CREATE OR REPLACE FUNCTION public.notif_disparar_push(p_id_notificacao bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_url     text;
  v_segredo text;
BEGIN
  SELECT decrypted_secret INTO v_url
  FROM vault.decrypted_secrets WHERE name = 'notificacoes_url_funcao' LIMIT 1;
  SELECT decrypted_secret INTO v_segredo
  FROM vault.decrypted_secrets WHERE name = 'notificacoes_segredo' LIMIT 1;

  IF v_url IS NULL OR v_segredo IS NULL THEN
    RETURN; -- ainda não configurado: fica 'pendente'
  END IF;

  UPDATE public.notificacoes
  SET push_status = 'enviando', push_tentativas = push_tentativas + 1
  WHERE id_notificacao = p_id_notificacao;

  PERFORM net.http_post(
    url := v_url,
    body := jsonb_build_object('id_notificacao', p_id_notificacao),
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-notificacoes-segredo', v_segredo),
    timeout_milliseconds := 10000
  );
EXCEPTION WHEN others THEN
  RAISE WARNING '[notificacoes] falha ao disparar push %: %', p_id_notificacao, SQLERRM;
END;
$$;

CREATE OR REPLACE FUNCTION public.trg_notificacao_criada()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.push_status = 'pendente' THEN
    PERFORM public.notif_disparar_push(NEW.id_notificacao);
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_notificacao_criada ON public.notificacoes;
CREATE TRIGGER trg_notificacao_criada
  AFTER INSERT ON public.notificacoes
  FOR EACH ROW EXECUTE FUNCTION public.trg_notificacao_criada();

-- Reenvio: pendentes (Vault ainda não configurado), falhas (rede/FCM) e
-- 'enviando' presos há mais de 5 min. Até 5 tentativas, nas últimas 24 h.
CREATE OR REPLACE FUNCTION public.reenviar_pushes_pendentes()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  r record;
  v_qtd integer := 0;
BEGIN
  FOR r IN
    SELECT id_notificacao FROM public.notificacoes
    WHERE data_criacao > now() - interval '24 hours'
      AND push_tentativas < 5
      AND (push_status IN ('pendente', 'falhou')
           OR (push_status = 'enviando' AND data_criacao < now() - interval '5 minutes'))
    ORDER BY data_criacao
    LIMIT 200
  LOOP
    PERFORM public.notif_disparar_push(r.id_notificacao);
    v_qtd := v_qtd + 1;
  END LOOP;
  RETURN v_qtd;
END;
$$;

-- 6) Solicitação ----------------------------------------------------------------------
-- Profissional recebe uma nova solicitação (as que nascem do Radar são
-- avisadas pela proposta aceita, no passo 8).
CREATE OR REPLACE FUNCTION public.trg_notif_solicitacao_nova()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_cliente  record;
  v_servico  text;
  v_detalhe  text;
  v_dest     bigint;
BEGIN
  IF NEW.fk_solicitacao_geografica IS NOT NULL THEN
    RETURN NEW;
  END IF;

  SELECT u.nome, NULLIF(NULLIF(u.foto_perfil_url, ''), 'null') AS foto
    INTO v_cliente
  FROM public.usuarios u WHERE u.id_usuario = NEW.fk_usuario;

  v_servico := public.notif_titulo_servico(NEW.id_solicitacao);
  v_detalhe := concat_ws(' • ',
    v_servico,
    NULLIF(NEW.tipo_execucao, ''),
    CASE WHEN NEW.data_agendada IS NOT NULL
         THEN to_char(NEW.data_agendada, 'DD/MM') ||
              coalesce(' às ' || to_char(NEW.hora_agendada, 'HH24:MI'), '')
    END);

  FOR v_dest IN
    SELECT x.fk_usuario
    FROM public.notif_usuarios_profissionais(NEW.fk_profissional, NEW.fk_grupo_empresa) x
    WHERE x.fk_usuario IS DISTINCT FROM NEW.fk_usuario
  LOOP
    PERFORM public.criar_notificacao(
      v_dest, 'Solicitação',
      'Nova solicitação de ' || coalesce(v_cliente.nome, 'um cliente'),
      v_detalhe,
      'solicitacao_estado', v_cliente.foto,
      NEW.id_solicitacao, NULL, NULL, NEW.fk_status,
      jsonb_build_object(
        'id_solicitacao', NEW.id_solicitacao,
        'papel', 'profissional',
        'evento', 'nova',
        'nome_cliente', v_cliente.nome,
        'servico', v_servico),
      format('sol_nova:%s:%s', NEW.id_solicitacao, v_dest));
  END LOOP;
  RETURN NEW;
EXCEPTION WHEN others THEN
  RAISE WARNING '[notificacoes] solicitacao nova %: %', NEW.id_solicitacao, SQLERRM;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_notif_solicitacao_nova ON public.solicitacoes;
CREATE TRIGGER trg_notif_solicitacao_nova
  AFTER INSERT ON public.solicitacoes
  FOR EACH ROW EXECUTE FUNCTION public.trg_notif_solicitacao_nova();

-- Mudança de status: cliente sempre; profissional só em 3, 5 e 38.
CREATE OR REPLACE FUNCTION public.trg_notif_solicitacao_status()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_status   text;
  v_tipo     text;
  v_servico  text;
  v_cliente  record;
  v_prof_nome text;
  v_prof_foto text;
  v_titulo   text;
  v_texto    text;
  v_dest     bigint;
  v_minuto   text := to_char(date_trunc('minute', now()), 'YYYYMMDDHH24MI');
  v_retirada boolean := lower(coalesce(NEW.tipo_execucao, '')) LIKE '%retirad%';
BEGIN
  IF NEW.fk_status IS NOT DISTINCT FROM OLD.fk_status THEN
    RETURN NEW;
  END IF;

  SELECT s.status::text, s.tipo_status::text INTO v_status, v_tipo
  FROM public.status s WHERE s.id_status = NEW.fk_status;
  IF v_tipo IS DISTINCT FROM 'Serviço' THEN
    RETURN NEW;
  END IF;

  v_servico := public.notif_titulo_servico(NEW.id_solicitacao);

  SELECT u.nome, NULLIF(NULLIF(u.foto_perfil_url, ''), 'null') AS foto
    INTO v_cliente
  FROM public.usuarios u WHERE u.id_usuario = NEW.fk_usuario;

  IF NEW.fk_grupo_empresa IS NOT NULL THEN
    SELECT g.nome_empresa, NULLIF(g.foto_url_empresa, '')
      INTO v_prof_nome, v_prof_foto
    FROM public.grupo_empresa g WHERE g.id_grupo_empresa = NEW.fk_grupo_empresa;
  ELSE
    SELECT u.nome, NULLIF(NULLIF(u.foto_perfil_url, ''), 'null')
      INTO v_prof_nome, v_prof_foto
    FROM public.dados_profissionais dp
    JOIN public.usuarios u ON u.id_usuario = dp.fk_usuario
    WHERE dp.id_profissional = NEW.fk_profissional;
  END IF;

  -- Cliente: toda mudança.
  v_titulo := CASE NEW.fk_status
    WHEN 1  THEN 'Pedido enviado'
    WHEN 2  THEN 'Pedido aceito! Falta o pagamento'
    WHEN 3  THEN 'Pagamento confirmado'
    WHEN 4  THEN 'Serviço em andamento'
    WHEN 5  THEN 'O profissional está aguardando você'
    WHEN 6  THEN 'Serviço concluído'
    WHEN 7  THEN 'Pedido cancelado'
    WHEN 30 THEN 'Pedido recusado'
    WHEN 31 THEN 'Pedido aceito'
    WHEN 32 THEN 'Aguardando o deslocamento'
    WHEN 33 THEN 'O profissional está a caminho'
    WHEN 34 THEN 'O profissional chegou'
    WHEN 35 THEN CASE WHEN v_retirada THEN 'Pronto para retirada'
                      ELSE 'Serviço pronto, aguardando devolução' END
    WHEN 36 THEN 'Seu item está a caminho'
    WHEN 37 THEN 'A devolução chegou'
    WHEN 38 THEN 'Você está a caminho'
    ELSE coalesce(v_status, 'Pedido atualizado')
  END;
  v_texto := concat_ws(' • ', v_servico, coalesce(v_prof_nome, 'Profissional'),
                       'Status: ' || coalesce(v_status, '—'));

  PERFORM public.criar_notificacao(
    NEW.fk_usuario, 'Solicitação', v_titulo, v_texto,
    'detalhes_pedido', v_prof_foto,
    NEW.id_solicitacao, NULL, NULL, NEW.fk_status,
    jsonb_build_object(
      'id_solicitacao', NEW.id_solicitacao,
      'papel', 'cliente',
      'evento', 'status',
      'status', v_status,
      'servico', v_servico),
    format('sol_status:%s:%s>%s:%s:%s', NEW.id_solicitacao, OLD.fk_status,
           NEW.fk_status, NEW.fk_usuario, v_minuto));

  -- Profissional: só Pago (3), Aguardando Cliente (5) e Cliente Deslocando (38).
  IF NEW.fk_status IN (3, 5, 38) THEN
    v_titulo := CASE NEW.fk_status
      WHEN 3  THEN 'Pagamento recebido!'
      WHEN 5  THEN coalesce(v_cliente.nome, 'O cliente') || ' está aguardando você'
      WHEN 38 THEN coalesce(v_cliente.nome, 'O cliente') || ' está a caminho'
    END;
    v_texto := CASE NEW.fk_status
      WHEN 3 THEN coalesce(v_cliente.nome, 'O cliente') || ' pagou ' || v_servico ||
                  coalesce(' (' || public.notif_formatar_reais(NEW.valor_final) || ')', '') ||
                  '. Já pode começar!'
      ELSE concat_ws(' • ', v_servico, 'Status: ' || v_status)
    END;

    FOR v_dest IN
      SELECT x.fk_usuario
      FROM public.notif_usuarios_profissionais(NEW.fk_profissional, NEW.fk_grupo_empresa) x
      WHERE x.fk_usuario IS DISTINCT FROM NEW.fk_usuario
    LOOP
      PERFORM public.criar_notificacao(
        v_dest, 'Solicitação', v_titulo, v_texto,
        'solicitacao_estado', v_cliente.foto,
        NEW.id_solicitacao, NULL, NULL, NEW.fk_status,
        jsonb_build_object(
          'id_solicitacao', NEW.id_solicitacao,
          'papel', 'profissional',
          'evento', 'status',
          'status', v_status,
          'nome_cliente', v_cliente.nome,
          'servico', v_servico),
        format('sol_status:%s:%s>%s:%s:%s', NEW.id_solicitacao, OLD.fk_status,
               NEW.fk_status, v_dest, v_minuto));
    END LOOP;
  END IF;

  RETURN NEW;
EXCEPTION WHEN others THEN
  RAISE WARNING '[notificacoes] status solicitacao %: %', NEW.id_solicitacao, SQLERRM;
  RETURN NEW;
END;
$$;

