-- 9) Sistema (diário, pg_cron) --------------------------------------------------------
-- Uma notificação por pendência por dia, enquanto ela existir. Ao preencher,
-- a pendência some e o envio para naturalmente.
CREATE OR REPLACE FUNCTION public.gerar_notificacoes_sistema()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  u         record;
  v_hoje    text := to_char(timezone('America/Sao_Paulo', now()), 'YYYY-MM-DD');
  v_qtd     integer := 0;
  v_faltam  text[];
  v_perfil  text;
  v_prof    public.dados_profissionais%ROWTYPE;
  v_grupo   public.grupo_empresa%ROWTYPE;
  v_tem_end boolean;
BEGIN
  FOR u IN
    SELECT us.id_usuario, us.nome, us.tipo_conta::text AS tipo_conta,
           us.fk_email, us.fk_telefone,
           NULLIF(NULLIF(trim(coalesce(us.foto_perfil_url, '')), ''), 'null') AS foto
    FROM public.usuarios us
    WHERE us.auth_id IS NOT NULL
  LOOP
    -- Dados pessoais (cliente e profissional).
    v_faltam := ARRAY[]::text[];
    IF u.fk_telefone IS NULL THEN v_faltam := v_faltam || 'telefone'; END IF;
    IF u.fk_email IS NULL THEN v_faltam := v_faltam || 'e-mail'; END IF;
    IF u.foto IS NULL THEN v_faltam := v_faltam || 'foto de perfil'; END IF;
    IF array_length(v_faltam, 1) > 0
       AND NOT public.notif_sistema_recente(u.id_usuario, 'dados_pessoais') THEN
      PERFORM public.criar_notificacao(
        u.id_usuario, 'Sistema', 'Complete seus dados pessoais',
        'Para uma melhor experiência, informe: ' || array_to_string(v_faltam, ', ') || '.',
        'editar_informacoes', NULL, NULL, NULL, NULL, NULL,
        jsonb_build_object('pendencia', 'dados_pessoais', 'itens', to_jsonb(v_faltam)),
        format('sis:dados_pessoais:%s:%s', u.id_usuario, v_hoje));
      v_qtd := v_qtd + 1;
    END IF;

    -- Endereço (qualquer um: pessoal, comercial ou da empresa).
    SELECT EXISTS (
             SELECT 1 FROM public.ass_usuario_endereco a WHERE a.fk_usuario = u.id_usuario)
        OR EXISTS (
             SELECT 1 FROM public.ass_profissional_endereco a
             JOIN public.dados_profissionais dp ON dp.id_profissional = a.fk_profissional
             WHERE dp.fk_usuario = u.id_usuario)
        OR EXISTS (
             SELECT 1 FROM public.ass_grupo_empresa_endereco a
             JOIN public.grupo_empresa g ON g.id_grupo_empresa = a.fk_grupo_empresa
             JOIN public.dados_profissionais dp
               ON dp.fk_perfil = g.fk_perfil OR dp.fk_grupo_empresa = g.id_grupo_empresa
             WHERE dp.fk_usuario = u.id_usuario)
      INTO v_tem_end;
    IF NOT v_tem_end AND NOT public.notif_sistema_recente(u.id_usuario, 'endereco') THEN
      PERFORM public.criar_notificacao(
        u.id_usuario, 'Sistema', 'Cadastre um endereço',
        'Com um endereço salvo, os pedidos e o Radar funcionam melhor para você.',
        'meus_enderecos', NULL, NULL, NULL, NULL, NULL,
        jsonb_build_object('pendencia', 'endereco'),
        format('sis:endereco:%s:%s', u.id_usuario, v_hoje));
      v_qtd := v_qtd + 1;
    END IF;

    CONTINUE WHEN u.tipo_conta IS DISTINCT FROM 'Profissional';

    -- Perfil ativo = o do aparelho usado por último (padrão: independente).
    SELECT d.perfil_ativo INTO v_perfil
    FROM public.dispositivos_notificacao d
    WHERE d.fk_usuario = u.id_usuario
    ORDER BY d.data_atualizacao DESC
    LIMIT 1;
    v_perfil := CASE WHEN v_perfil = 'empresa' THEN 'empresa' ELSE 'independente' END;

    v_prof := NULL;
    v_grupo := NULL;
    SELECT * INTO v_prof FROM public.dados_profissionais dp
    WHERE dp.fk_usuario = u.id_usuario ORDER BY dp.id_profissional LIMIT 1;
    CONTINUE WHEN v_prof.id_profissional IS NULL;

    IF v_perfil = 'empresa' THEN
      -- Só o dono edita os dados da empresa.
      SELECT * INTO v_grupo FROM public.grupo_empresa g
      WHERE g.fk_perfil = v_prof.fk_perfil LIMIT 1;
      IF v_grupo.id_grupo_empresa IS NULL THEN
        v_perfil := 'independente';
      END IF;
    END IF;

    IF v_perfil = 'empresa' THEN
      v_qtd := v_qtd + public.notif_sistema_item(u.id_usuario, v_hoje, 'empresa',
        'pagamento', coalesce(trim(v_grupo.pagamento_aceito), '') = '',
