  IF NEW.fk_status IS NOT DISTINCT FROM OLD.fk_status THEN
    RETURN NEW;
  END IF;
  SELECT s.status::text, s.tipo_status::text INTO v_status, v_tipo
  FROM public.status s WHERE s.id_status = NEW.fk_status;
  IF v_tipo IS DISTINCT FROM 'Solicitação Geográfica' THEN
    RETURN NEW;
  END IF;

  IF NEW.fk_status = 44 THEN
    -- Proposta recebida: valor + quem mandou.
    SELECT p.valor,
           CASE WHEN p.fk_grupo_empresa IS NOT NULL THEN g.nome_empresa ELSE u.nome END,
           CASE WHEN p.fk_grupo_empresa IS NOT NULL THEN NULLIF(g.foto_url_empresa, '')
                ELSE NULLIF(NULLIF(u.foto_perfil_url, ''), 'null') END
      INTO v_prop_valor, v_prop_nome, v_foto
    FROM public.propostas_geograficas p
    LEFT JOIN public.grupo_empresa g ON g.id_grupo_empresa = p.fk_grupo_empresa
    LEFT JOIN public.dados_profissionais dp ON dp.id_profissional = p.fk_profissional
    LEFT JOIN public.usuarios u ON u.id_usuario = dp.fk_usuario
    WHERE p.fk_solicitacao_geografica = NEW.id_solicitacao_geografica
      AND p.fk_status = 44
    ORDER BY p.data_envio DESC
    LIMIT 1;
  END IF;

  v_titulo := CASE NEW.fk_status
    WHEN 39 THEN CASE WHEN OLD.fk_status = 44
                      THEN 'Seu pedido voltou para o Radar'
                      ELSE 'Pedido publicado no Radar' END
    WHEN 40 THEN 'Pedido do Radar concluído'
    WHEN 41 THEN 'Seu pedido foi visualizado'
    WHEN 42 THEN 'Proposta aceita! Falta o pagamento'
    WHEN 43 THEN 'Pedido do Radar cancelado'
    WHEN 44 THEN 'Você recebeu uma proposta!'
    ELSE coalesce(v_status, 'Pedido do Radar atualizado')
  END;
  v_texto := CASE NEW.fk_status
    WHEN 39 THEN CASE WHEN OLD.fk_status = 44
                      THEN '"' || NEW.titulo || '" está visível de novo para os profissionais da área.'
                      ELSE '"' || NEW.titulo || '" está visível para os profissionais da área.' END
    WHEN 40 THEN '"' || NEW.titulo || '" foi finalizado. Você já pode fazer um novo pedido.'
    WHEN 41 THEN 'Um profissional viu "' || NEW.titulo || '".'
    WHEN 42 THEN 'Pague "' || NEW.titulo || '" para o serviço começar.'
    WHEN 43 THEN '"' || NEW.titulo || '" não está mais no Radar.'
    WHEN 44 THEN coalesce(v_prop_nome, 'Um profissional') || ' quer fazer "' ||
                 NEW.titulo || '" por ' || public.notif_formatar_reais(v_prop_valor) || '.'
    ELSE NEW.titulo
  END;

  PERFORM public.criar_notificacao(
    NEW.fk_usuario, 'radar_cliente', v_titulo, v_texto,
    'radar_cliente', v_foto,
    NULL, NULL, NEW.id_solicitacao_geografica, NEW.fk_status,
    jsonb_build_object(
      'id_solicitacao_geografica', NEW.id_solicitacao_geografica,
      'papel', 'cliente',
      'evento', 'status',
      'status', v_status),
    format('radar_status:%s:%s>%s:%s', NEW.id_solicitacao_geografica,
           OLD.fk_status, NEW.fk_status,
           to_char(date_trunc('minute', now()), 'YYYYMMDDHH24MI')));
  RETURN NEW;
EXCEPTION WHEN others THEN
  RAISE WARNING '[notificacoes] radar status %: %', NEW.id_solicitacao_geografica, SQLERRM;
  RETURN NEW;
END;
$$;

