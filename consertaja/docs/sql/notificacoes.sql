-- radar_prof: pedido novo dentro do raio, com uma função do profissional.
-- (Desde migration_oficios_por_categoria.sql o Radar compara pela FUNÇÃO:
-- comparar pelo ofício/categoria avisaria um Encanador de pedido de
-- Eletricista.)
CREATE OR REPLACE FUNCTION public.trg_notif_radar_novo()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_cliente record;
  v_funcao  text;
  r         record;
BEGIN
  SELECT u.nome, NULLIF(NULLIF(u.foto_perfil_url, ''), 'null') AS foto
    INTO v_cliente
  FROM public.usuarios u WHERE u.id_usuario = NEW.fk_usuario;
  SELECT f.funcao INTO v_funcao FROM public.funcoes f WHERE f.id_funcao = NEW.fk_funcao;

  FOR r IN
    SELECT DISTINCT ON (l.fk_usuario)
           l.fk_usuario, l.tipo,
           public.radar_km(NEW.latitude, NEW.longitude, l.latitude, l.longitude) AS dist
    FROM public.radar_locais_perfis() l
    WHERE l.fk_usuario IS NOT NULL
      AND l.fk_usuario IS DISTINCT FROM NEW.fk_usuario
      AND public.radar_km(NEW.latitude, NEW.longitude, l.latitude, l.longitude) <= NEW.raio_km
      AND NEW.fk_funcao IN (
        SELECT f.fk_funcao FROM public.radar_funcoes_perfil(l.id_profissional, l.id_grupo_empresa) f)
    ORDER BY l.fk_usuario,
             public.radar_km(NEW.latitude, NEW.longitude, l.latitude, l.longitude)
  LOOP
    PERFORM public.criar_notificacao(
      r.fk_usuario, 'radar_prof',
      'Novo pedido no Radar: ' || NEW.titulo,
      concat_ws(' • ',
        coalesce(v_cliente.nome, 'Cliente'),
        'a ' || replace(to_char(r.dist, 'FM990.0'), '.', ',') || ' km de você',
        v_funcao),
      'radar_profissional', v_cliente.foto,
      NULL, NULL, NEW.id_solicitacao_geografica, NEW.fk_status,
      jsonb_build_object(
        'id_solicitacao_geografica', NEW.id_solicitacao_geografica,
        'papel', 'profissional',
        'evento', 'novo',
        'perfil', r.tipo,
        'distancia_km', round(r.dist::numeric, 1),
        'nome_cliente', v_cliente.nome,
        'funcao', v_funcao),
      format('radar_novo:%s:%s', NEW.id_solicitacao_geografica, r.fk_usuario));
  END LOOP;
  RETURN NEW;
EXCEPTION WHEN others THEN
  RAISE WARNING '[notificacoes] radar novo %: %', NEW.id_solicitacao_geografica, SQLERRM;
  RETURN NEW;
END;
$$;

