-- ============================================================================
-- ConsertaJá — Solicitação Geográfica (aba "Radar" do cliente)
--
-- O cliente descreve o problema, escolhe a função (área do pedido), anexa
-- imagens e a solicitação vai para os profissionais/empresas com essa função
-- num raio de 5 km da localização dele.
--
-- Cria:
--   1. Status 39/41/42/43 (tipo_status = 'Solicitação Geográfica')
--   2. Tabela solicitacoes_geograficas
--   3. Tabela solicitacoes_geograficas_profissionais (quem foi notificado e o
--      status de cada um: Enviada/Visualizada/Respondida — 3º design)
--   4. solicitacoes.fk_solicitacao_geografica (nullable)
--   5. RPC profissionais_proximos_geo (perfis no raio com a função)
--   6. RPC criar_solicitacao_geografica (cria + notifica numa transação)
--   7. RLS
--
-- Rode inteiro no SQL Editor do Supabase. Depende de migration_funcoes.sql.
-- ============================================================================

BEGIN;

-- 1) Status ------------------------------------------------------------------
INSERT INTO public.status (id_status, tipo_status, status)
VALUES
  (39, 'Solicitação Geográfica', 'Solicitada'),
  (41, 'Solicitação Geográfica', 'Visualizada'),
  (42, 'Solicitação Geográfica', 'Respondida'),
  (43, 'Solicitação Geográfica', 'Cancelada')
ON CONFLICT (id_status) DO UPDATE
SET tipo_status = EXCLUDED.tipo_status,
    status      = EXCLUDED.status;

-- 2) Solicitação geográfica --------------------------------------------------
CREATE TABLE IF NOT EXISTS public.solicitacoes_geograficas (
  id_solicitacao_geografica bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_usuario      bigint NOT NULL REFERENCES public.usuarios(id_usuario),
  descricao       text   NOT NULL CHECK (char_length(trim(descricao)) BETWEEN 1 AND 500),
  fk_funcao       bigint NOT NULL REFERENCES public.funcoes(id_funcao),
  fk_oficio       bigint REFERENCES public.oficios(id_oficio),
  -- URLs públicas das imagens no bucket 'Imagens Anexadas Cliente'.
  img_solicitacao text[] NOT NULL DEFAULT '{}',
  fk_status       bigint NOT NULL DEFAULT 39 REFERENCES public.status(id_status),
  -- Centro e raio do círculo do mapa.
  latitude        double precision NOT NULL,
  longitude       double precision NOT NULL,
  raio_km         numeric(5,2) NOT NULL DEFAULT 5,
  data_criacao    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS solicitacoes_geograficas_fk_usuario_idx
  ON public.solicitacoes_geograficas (fk_usuario, data_criacao DESC);

-- 3) Perfis notificados (profissional independente OU empresa) ---------------
CREATE TABLE IF NOT EXISTS public.solicitacoes_geograficas_profissionais (
  id_notificacao_geo        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_solicitacao_geografica bigint NOT NULL
    REFERENCES public.solicitacoes_geograficas(id_solicitacao_geografica)
    ON DELETE CASCADE,
  fk_profissional  bigint REFERENCES public.dados_profissionais(id_profissional),
  fk_grupo_empresa bigint REFERENCES public.grupo_empresa(id_grupo_empresa),
  -- 39 = Enviada (Solicitada), 41 = Visualizada, 42 = Respondida
  fk_status        bigint NOT NULL DEFAULT 39 REFERENCES public.status(id_status),
  distancia_km     numeric(6,2),
  data_criacao     timestamptz NOT NULL DEFAULT now(),
  data_visualizacao timestamptz,
  data_resposta    timestamptz,
  CONSTRAINT sgp_um_perfil_check CHECK (
    (fk_profissional IS NOT NULL)::int + (fk_grupo_empresa IS NOT NULL)::int = 1
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS sgp_prof_unico
  ON public.solicitacoes_geograficas_profissionais (fk_solicitacao_geografica, fk_profissional)
  WHERE fk_profissional IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS sgp_empresa_unico
  ON public.solicitacoes_geograficas_profissionais (fk_solicitacao_geografica, fk_grupo_empresa)
  WHERE fk_grupo_empresa IS NOT NULL;

-- 4) Vínculo na solicitação de serviço --------------------------------------
ALTER TABLE public.solicitacoes
  ADD COLUMN IF NOT EXISTS fk_solicitacao_geografica bigint NULL
  REFERENCES public.solicitacoes_geograficas(id_solicitacao_geografica)
  ON DELETE SET NULL;

-- Helper: id_usuario da sessão.
CREATE OR REPLACE FUNCTION public.meu_id_usuario()
RETURNS bigint
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT id_usuario FROM public.usuarios WHERE auth_id = auth.uid() LIMIT 1
$$;
GRANT EXECUTE ON FUNCTION public.meu_id_usuario() TO authenticated;

-- 5) Perfis próximos ----------------------------------------------------------
-- Profissional independente = dados_profissionais sem empresa OU dono de
-- empresa (o perfil pessoal do dono aparece separado do perfil da empresa).
-- Membros de empresa não aparecem sozinhos: entram pelo perfil da empresa.
CREATE OR REPLACE FUNCTION public.profissionais_proximos_geo(
  p_lat       double precision,
  p_lng       double precision,
  p_raio_km   double precision DEFAULT 5,
  p_fk_funcao bigint DEFAULT NULL
)
RETURNS TABLE (
  tipo             text,   -- 'profissional' | 'empresa'
  id_profissional  bigint,
  id_grupo_empresa bigint,
  nome             text,
  foto_url         text,
  tag_empresa      text,
  cor_tag_empresa  text,
  latitude         double precision,
  longitude        double precision,
  distancia_km     double precision,
  nota             numeric,
  ultima_conexao   timestamptz
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
WITH funcao AS (
  SELECT f.fk_oficio FROM public.funcoes f WHERE f.id_funcao = p_fk_funcao
),
eu AS (SELECT public.meu_id_usuario() AS id_usuario),

-- Perfis independentes (inclui o perfil pessoal do dono de empresa)
prof AS (
  SELECT dp.id_profissional, dp.fk_usuario
  FROM public.dados_profissionais dp
  WHERE (
      dp.fk_grupo_empresa IS NULL
      OR EXISTS (SELECT 1 FROM public.grupo_empresa g
                 WHERE g.fk_perfil = dp.fk_perfil)
    )
    AND dp.fk_usuario IS DISTINCT FROM (SELECT id_usuario FROM eu)
    AND (
      p_fk_funcao IS NULL OR EXISTS (
        SELECT 1 FROM public.ass_oficio_profissional aop
        WHERE aop.fk_profissional = dp.id_profissional
          AND aop.fk_oficio = (SELECT fk_oficio FROM funcao)
      )
    )
),
prof_loc AS (
  SELECT p.id_profissional, p.fk_usuario,
         NULLIF(e.latitude::text, '')::double precision  AS lat,
         NULLIF(e.longitude::text, '')::double precision AS lng
  FROM prof p
  CROSS JOIN LATERAL (
    SELECT en.latitude, en.longitude FROM (
      -- 1º endereço comercial (CNPJ); 2º endereço ativo pessoal
      SELECT ape.fk_endereco, 0 AS ordem, ape.endereco_ativo
      FROM public.ass_profissional_endereco ape
      WHERE ape.fk_profissional = p.id_profissional
      UNION ALL
      SELECT aue.fk_endereco, 1, aue.endereco_ativo
      FROM public.ass_usuario_endereco aue
      WHERE aue.fk_usuario = p.fk_usuario AND aue.endereco_ativo = true
    ) v
    JOIN public.enderecos en ON en.id_endereco = v.fk_endereco
    WHERE en.latitude IS NOT NULL AND en.longitude IS NOT NULL
    ORDER BY v.ordem, v.endereco_ativo DESC
    LIMIT 1
  ) e
),

-- Perfis de empresa
emp AS (
  SELECT g.id_grupo_empresa, g.nome_empresa, g.foto_url_empresa,
         g.tag_empresa, g.cor_tag_empresa, g.fk_perfil
  FROM public.grupo_empresa g
  WHERE p_fk_funcao IS NULL
     OR EXISTS (
       SELECT 1 FROM public.ass_oficio_grupo_empresa aoe
       WHERE aoe.fk_grupo_empresa = g.id_grupo_empresa
         AND aoe.fk_oficio = (SELECT fk_oficio FROM funcao)
     )
     OR EXISTS (
       SELECT 1
       FROM public.dados_profissionais dp
       JOIN public.ass_oficio_profissional aop
         ON aop.fk_profissional = dp.id_profissional
       WHERE (dp.fk_grupo_empresa = g.id_grupo_empresa OR dp.fk_perfil = g.fk_perfil)
         AND aop.fk_oficio = (SELECT fk_oficio FROM funcao)
     )
),
emp_loc AS (
  SELECT m.*,
         NULLIF(e.latitude::text, '')::double precision  AS lat,
         NULLIF(e.longitude::text, '')::double precision AS lng
  FROM emp m
  CROSS JOIN LATERAL (
    SELECT en.latitude, en.longitude FROM (
      SELECT age.fk_endereco, 0 AS ordem, age.endereco_ativo
      FROM public.ass_grupo_empresa_endereco age
      WHERE age.fk_grupo_empresa = m.id_grupo_empresa
      UNION ALL
      -- legado: endereço Loja/Oficina/Outro do dono ou membros
      SELECT aue.fk_endereco, 1, aue.endereco_ativo
      FROM public.ass_usuario_endereco aue
      JOIN public.dados_profissionais dp ON dp.fk_usuario = aue.fk_usuario
      WHERE (dp.fk_grupo_empresa = m.id_grupo_empresa OR dp.fk_perfil = m.fk_perfil)
        AND aue.tipo_endereco::text IN ('Loja', 'Oficina', 'Outro')
    ) v
    JOIN public.enderecos en ON en.id_endereco = v.fk_endereco
    WHERE en.latitude IS NOT NULL AND en.longitude IS NOT NULL
    ORDER BY v.ordem, v.endereco_ativo DESC
    LIMIT 1
  ) e
),

perfis AS (
  SELECT 'profissional'::text AS tipo,
         pl.id_profissional, NULL::bigint AS id_grupo_empresa,
         u.nome::text AS nome,
         NULLIF(NULLIF(u.foto_perfil_url::text, ''), 'null') AS foto_url,
         NULL::text AS tag_empresa, NULL::text AS cor_tag_empresa,
         pl.lat, pl.lng,
         (SELECT round(avg(av.nota)::numeric, 1)
            FROM public.avaliacoes_solicitacao av
            JOIN public.solicitacoes s ON s.id_solicitacao = av.fk_solicitacao
           WHERE av.tipo_avaliacao::text = 'profissional'
             AND s.fk_profissional = pl.id_profissional) AS nota,
         u.ultima_conexao
  FROM prof_loc pl
  JOIN public.usuarios u ON u.id_usuario = pl.fk_usuario
  UNION ALL
  SELECT 'empresa', NULL, el.id_grupo_empresa,
         el.nome_empresa::text,
         NULLIF(el.foto_url_empresa::text, ''),
         NULLIF(el.tag_empresa::text, ''), NULLIF(el.cor_tag_empresa::text, ''),
         el.lat, el.lng,
         (SELECT round(avg(av.nota)::numeric, 1)
            FROM public.avaliacoes_solicitacao av
            JOIN public.solicitacoes s ON s.id_solicitacao = av.fk_solicitacao
           WHERE av.tipo_avaliacao::text = 'profissional'
             AND s.fk_grupo_empresa = el.id_grupo_empresa),
         (SELECT u.ultima_conexao
            FROM public.dados_profissionais dp
            JOIN public.usuarios u ON u.id_usuario = dp.fk_usuario
           WHERE dp.fk_perfil = el.fk_perfil
           LIMIT 1)
  FROM emp_loc el
),
com_distancia AS (
  SELECT p.*,
         -- Haversine (km)
         6371 * 2 * asin(sqrt(
           power(sin(radians(p.lat - p_lat) / 2), 2) +
           cos(radians(p_lat)) * cos(radians(p.lat)) *
           power(sin(radians(p.lng - p_lng) / 2), 2)
         )) AS dist
  FROM perfis p
  WHERE p.lat IS NOT NULL AND p.lng IS NOT NULL
)
SELECT tipo, id_profissional, id_grupo_empresa, nome, foto_url, tag_empresa,
       cor_tag_empresa, lat, lng, round(dist::numeric, 2)::double precision,
       nota, ultima_conexao
FROM com_distancia
WHERE dist <= p_raio_km
ORDER BY dist
LIMIT 60;
$$;

GRANT EXECUTE ON FUNCTION public.profissionais_proximos_geo(
  double precision, double precision, double precision, bigint
) TO authenticated;

-- 6) Criar solicitação + notificar perfis do raio (tudo ou nada) ------------
CREATE OR REPLACE FUNCTION public.criar_solicitacao_geografica(
  p_descricao       text,
  p_fk_funcao       bigint,
  p_img_solicitacao text[],
  p_lat             double precision,
  p_lng             double precision,
  p_raio_km         double precision DEFAULT 5
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_usuario bigint := public.meu_id_usuario();
  v_oficio  bigint;
  v_id      bigint;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Sessão expirada. Entre novamente.' USING ERRCODE = '42501';
  END IF;
  IF coalesce(trim(p_descricao), '') = '' THEN
    RAISE EXCEPTION 'Descreva o que você precisa.';
  END IF;
  IF coalesce(array_length(p_img_solicitacao, 1), 0) = 0 THEN
    RAISE EXCEPTION 'Anexe pelo menos uma imagem.';
  END IF;

  SELECT fk_oficio INTO v_oficio FROM public.funcoes WHERE id_funcao = p_fk_funcao;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Área do pedido inválida.';
  END IF;

  INSERT INTO public.solicitacoes_geograficas
    (fk_usuario, descricao, fk_funcao, fk_oficio, img_solicitacao,
     latitude, longitude, raio_km)
  VALUES
    (v_usuario, trim(p_descricao), p_fk_funcao, v_oficio, p_img_solicitacao,
     p_lat, p_lng, coalesce(p_raio_km, 5))
  RETURNING id_solicitacao_geografica INTO v_id;

  INSERT INTO public.solicitacoes_geograficas_profissionais
    (fk_solicitacao_geografica, fk_profissional, fk_grupo_empresa, distancia_km)
  SELECT v_id, p.id_profissional, p.id_grupo_empresa, p.distancia_km
  FROM public.profissionais_proximos_geo(p_lat, p_lng, coalesce(p_raio_km, 5), p_fk_funcao) p;

  RETURN v_id;
END;
$$;

GRANT EXECUTE ON FUNCTION public.criar_solicitacao_geografica(
  text, bigint, text[], double precision, double precision, double precision
) TO authenticated;

-- 7) RLS ---------------------------------------------------------------------
ALTER TABLE public.solicitacoes_geograficas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.solicitacoes_geograficas_profissionais ENABLE ROW LEVEL SECURITY;

-- O perfil (profissional ou empresa) da sessão foi notificado?
CREATE OR REPLACE FUNCTION public.sou_notificado_geo(
  p_fk_profissional bigint, p_fk_grupo_empresa bigint
)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.dados_profissionais dp
    WHERE dp.fk_usuario = public.meu_id_usuario()
      AND (
        dp.id_profissional = p_fk_profissional
        OR (p_fk_grupo_empresa IS NOT NULL AND (
              dp.fk_grupo_empresa = p_fk_grupo_empresa
              OR EXISTS (SELECT 1 FROM public.grupo_empresa g
                         WHERE g.id_grupo_empresa = p_fk_grupo_empresa
                           AND g.fk_perfil = dp.fk_perfil)))
      )
  )
$$;
GRANT EXECUTE ON FUNCTION public.sou_notificado_geo(bigint, bigint) TO authenticated;

DROP POLICY IF EXISTS "sg_select" ON public.solicitacoes_geograficas;
CREATE POLICY "sg_select" ON public.solicitacoes_geograficas
  FOR SELECT TO authenticated
  USING (
    fk_usuario = public.meu_id_usuario()
    OR EXISTS (
      SELECT 1 FROM public.solicitacoes_geograficas_profissionais n
      WHERE n.fk_solicitacao_geografica = solicitacoes_geograficas.id_solicitacao_geografica
        AND public.sou_notificado_geo(n.fk_profissional, n.fk_grupo_empresa)
    )
  );

-- O cliente só altera a própria solicitação (ex.: cancelar → 43).
DROP POLICY IF EXISTS "sg_update_dono" ON public.solicitacoes_geograficas;
CREATE POLICY "sg_update_dono" ON public.solicitacoes_geograficas
  FOR UPDATE TO authenticated
  USING (fk_usuario = public.meu_id_usuario())
  WITH CHECK (fk_usuario = public.meu_id_usuario());

-- (INSERT só pela RPC criar_solicitacao_geografica.)

DROP POLICY IF EXISTS "sgp_select" ON public.solicitacoes_geograficas_profissionais;
CREATE POLICY "sgp_select" ON public.solicitacoes_geograficas_profissionais
  FOR SELECT TO authenticated
  USING (
    EXISTS (SELECT 1 FROM public.solicitacoes_geograficas s
            WHERE s.id_solicitacao_geografica = fk_solicitacao_geografica
              AND s.fk_usuario = public.meu_id_usuario())
    OR public.sou_notificado_geo(fk_profissional, fk_grupo_empresa)
  );

-- O cliente escolhe quem notificar (marca/desmarca perfis).
DROP POLICY IF EXISTS "sgp_insert_dono" ON public.solicitacoes_geograficas_profissionais;
CREATE POLICY "sgp_insert_dono" ON public.solicitacoes_geograficas_profissionais
  FOR INSERT TO authenticated
  WITH CHECK (
    EXISTS (SELECT 1 FROM public.solicitacoes_geograficas s
            WHERE s.id_solicitacao_geografica = fk_solicitacao_geografica
              AND s.fk_usuario = public.meu_id_usuario()
              AND s.fk_status <> 43)
  );

DROP POLICY IF EXISTS "sgp_delete_dono" ON public.solicitacoes_geograficas_profissionais;
CREATE POLICY "sgp_delete_dono" ON public.solicitacoes_geograficas_profissionais
  FOR DELETE TO authenticated
  USING (
    EXISTS (SELECT 1 FROM public.solicitacoes_geograficas s
            WHERE s.id_solicitacao_geografica = fk_solicitacao_geografica
              AND s.fk_usuario = public.meu_id_usuario())
  );

-- O profissional notificado marca Visualizada (41) / Respondida (42).
DROP POLICY IF EXISTS "sgp_update_notificado" ON public.solicitacoes_geograficas_profissionais;
CREATE POLICY "sgp_update_notificado" ON public.solicitacoes_geograficas_profissionais
  FOR UPDATE TO authenticated
  USING (public.sou_notificado_geo(fk_profissional, fk_grupo_empresa))
  WITH CHECK (public.sou_notificado_geo(fk_profissional, fk_grupo_empresa));

COMMIT;

