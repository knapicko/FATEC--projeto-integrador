-- ============================================================================
-- ConsertaJá — Tabela `funcoes` + `fk_funcao` nos serviços
--
-- Antes: o serviço guardava `fk_oficios` e o app buscava `oficios.funcao`
--        para mostrar a função.
-- Agora: a função tem tabela própria (`funcoes`) e o serviço aponta direto
--        para ela via `fk_funcao`. `oficios` fica só com categoria/cor.
--
-- Mapeamento 1:1 com os dados atuais: cada ofício vira uma função com o
-- MESMO id (id_funcao = id_oficio), então nada que já usa id de ofício quebra.
--
-- Rode inteiro no SQL Editor do Supabase. Está dentro de uma transação:
-- se qualquer passo falhar, nada é alterado.
-- ============================================================================

BEGIN;

-- 1) Tabela funcoes ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.funcoes (
  id_funcao  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_oficio  bigint NOT NULL REFERENCES public.oficios(id_oficio),
  funcao     text   NOT NULL UNIQUE,
  descricao  text,
  img_funcao text
);

CREATE INDEX IF NOT EXISTS funcoes_fk_oficio_idx ON public.funcoes (fk_oficio);

-- 2) Copia as funções atuais de `oficios` (mesmo id) com uma descrição ------
INSERT INTO public.funcoes (id_funcao, fk_oficio, funcao, descricao, img_funcao)
SELECT o.id_oficio, o.id_oficio, o.funcao, d.descricao, NULL
FROM public.oficios o
LEFT JOIN (VALUES
  ('Encanador',               'Instala e conserta canos, torneiras, registros, caixas d''água e vazamentos.'),
  ('Eletricista',             'Faz instalações e reparos elétricos: tomadas, disjuntores, fiação e iluminação.'),
  ('Desentupidor',            'Desentope pias, ralos, vasos sanitários, esgotos e caixas de gordura.'),
  ('Reparador geral',         'Pequenos reparos domésticos: ajustes, trocas, fixações e manutenção em geral.'),
  ('Montador de móveis',      'Monta, desmonta e instala móveis planejados e de loja.'),
  ('Marceneiro',              'Fabrica, restaura e ajusta móveis e peças de madeira sob medida.'),
  ('Tapeceiro',               'Reforma estofados: troca de tecido, espuma e acabamento de sofás e cadeiras.'),
  ('Chaveiro',                'Abre portas, faz cópias de chaves e troca segredos de fechaduras.'),
  ('Instalador de fechadura', 'Instala e troca fechaduras comuns, tetra e eletrônicas.'),
  ('Vidraceiro',              'Corta, instala e troca vidros, espelhos, janelas e boxes.'),
  ('Serralheiro',             'Fabrica e conserta portões, grades, estruturas e peças metálicas.'),
  ('Sapateiro',               'Conserta calçados: solados, saltos, costuras e colagens.'),
  ('Costureira',              'Ajustes e consertos de roupas: barras, zíperes, bainhas e reformas.'),
  ('Lavador de tapete',       'Limpeza profunda e higienização de tapetes e carpetes.'),
  ('Lavador de colchão',      'Higienização de colchões, removendo ácaros, manchas e odores.'),
  ('Paneleiro',               'Conserta panelas: cabos, tampas, alças e válvulas de panela de pressão.'),
  ('Afiador',                 'Afia facas, tesouras, alicates e ferramentas de corte.'),
  ('Soldador de utensílios',  'Solda e recupera utensílios de metal do dia a dia.'),
  ('Funileiro',               'Conserta e fabrica peças de lata e chapa metálica, como calhas e utensílios.')
) AS d(funcao, descricao) ON d.funcao = o.funcao
WHERE o.funcao IS NOT NULL AND trim(o.funcao) <> ''
ON CONFLICT (funcao) DO NOTHING;

-- Ajusta a sequência para os próximos inserts não colidirem com os ids copiados.
SELECT setval(
  pg_get_serial_sequence('public.funcoes', 'id_funcao'),
  GREATEST((SELECT COALESCE(MAX(id_funcao), 0) FROM public.funcoes), 1)
);

-- 3) fk_funcao em servicos_profissional -------------------------------------
ALTER TABLE public.servicos_profissional
  ADD COLUMN IF NOT EXISTS fk_funcao bigint REFERENCES public.funcoes(id_funcao);

UPDATE public.servicos_profissional sp
SET fk_funcao = f.id_funcao
FROM public.funcoes f
WHERE sp.fk_funcao IS NULL AND f.fk_oficio = sp.fk_oficios;

CREATE INDEX IF NOT EXISTS servicos_profissional_fk_funcao_idx
  ON public.servicos_profissional (fk_funcao);

-- 4) fk_funcao em servicos_chat_temporarios ---------------------------------
ALTER TABLE public.servicos_chat_temporarios
  ADD COLUMN IF NOT EXISTS fk_funcao bigint
  REFERENCES public.funcoes(id_funcao) ON DELETE SET NULL;

UPDATE public.servicos_chat_temporarios t
SET fk_funcao = f.id_funcao
FROM public.funcoes f
WHERE t.fk_funcao IS NULL AND f.fk_oficio = t.fk_oficios;

-- 5) fk_funcao em servicos_catalogo (sugestões de serviço) -------------------
--    Também lia oficios.funcao, então precisa da mesma mudança.
ALTER TABLE public.servicos_catalogo
  ADD COLUMN IF NOT EXISTS fk_funcao bigint REFERENCES public.funcoes(id_funcao);

UPDATE public.servicos_catalogo c
SET fk_funcao = f.id_funcao
FROM public.funcoes f
WHERE c.fk_funcao IS NULL AND f.fk_oficio = c.fk_oficio;

-- 6) Leitura de funcoes liberada (igual a `oficios`) -------------------------
ALTER TABLE public.funcoes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "funcoes_select_publico" ON public.funcoes;
CREATE POLICY "funcoes_select_publico"
  ON public.funcoes FOR SELECT TO anon, authenticated
  USING (true);

GRANT SELECT ON public.funcoes TO anon, authenticated;

-- 7) Remove funcao e descricao de oficios -----------------------------------
--    Sem CASCADE de propósito: se alguma view depender delas, o script para
--    aqui e nada é aplicado.
ALTER TABLE public.oficios DROP COLUMN IF EXISTS funcao;
ALTER TABLE public.oficios DROP COLUMN IF EXISTS descricao;

COMMIT;

-- Faz o PostgREST enxergar a tabela/colunas novas imediatamente.
NOTIFY pgrst, 'reload schema';
